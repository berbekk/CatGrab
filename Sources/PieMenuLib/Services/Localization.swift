    /// Общий экземпляр, синхронизированный с `ConfigManager.shared.configuration.language`
    /// через Combine‑подписку в `AppDelegate`.
    @MainActor
    static let shared: LocalizationStore = {
        let language = ConfigManager.shared.configuration.language
        return LocalizationStore(language: language)
    }()

    @Published var language: AppLanguage

    init(language: AppLanguage) {
        self.language = language
    }

