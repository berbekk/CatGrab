import SwiftUI

/// Лапка, которой кот придерживает иконку в меню команд, — по рисунку `design/paw-grab.png`:
/// ладонь слева, четыре пальца с коготками вправо, между пальцами белые складки.
/// Контуры сняты с рисунка и заданы в квадрате 1×1 (рисунок вписан по высоте и отцентрован).
struct CatGrabPawView: View {
    let size: CGFloat

    /// Обводка как у мордочки (`PieCenterCatEyesView`): на тёмном центре меню без неё ладонь теряется.
    private static let outlineWhiteOpacity: CGFloat = 0.24
    private static let outlineWidth: CGFloat = 0.7

    var body: some View {
        ZStack {
            CatGrabPawShape(points: CatGrabPawGeometry.outline)
                .fill(Color.black)
                .overlay {
                    CatGrabPawShape(points: CatGrabPawGeometry.outline)
                        .stroke(Color.white.opacity(Self.outlineWhiteOpacity), lineWidth: Self.outlineWidth)
                }
            ForEach(CatGrabPawGeometry.creases.indices, id: \.self) { index in
                CatGrabPawShape(points: CatGrabPawGeometry.creases[index])
                    .fill(Color.white)
            }
        }
        .frame(width: size, height: size)
    }

    /// Доля ширины рисунка в квадрате — чтобы расставлять лапку по её настоящим краям.
    static let aspect: CGFloat = 463 / 526
}

/// Замкнутый многоугольник из точек в долях рамки: x, y, x, y, …
struct CatGrabPawShape: Shape {
    let points: [CGFloat]

    func path(in rect: CGRect) -> Path {
        var path = Path()
        guard points.count >= 6 else { return path }
        let mapped = stride(from: 0, to: points.count - 1, by: 2).map { i in
            CGPoint(x: rect.minX + points[i] * rect.width, y: rect.minY + points[i + 1] * rect.height)
        }
        path.addLines(mapped)
        path.closeSubpath()
        return path
    }
}

